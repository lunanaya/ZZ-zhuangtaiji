import assert from 'node:assert/strict';
globalThis.window=globalThis;
globalThis.WorldStateMachine={};
await import('../src/defaults.js');
await import('../src/storage.js');
await import('../src/state-logic.js');
await import('../src/plain-memory.js');
await import('../src/memory-view.js');
const W=WorldStateMachine;
const settings={enabled:true,injectionModules:structuredClone(W.Defaults.INJECTION_MODULES)};
W.Settings={get:()=>settings};
W.Context={latestUserMessage:()=>({content:'继续。'}),identityNames:()=>({user:'来客',char:'陆衡'})};
const secret='密函去向｜内容：密函藏在东楼｜不知情：陆衡、赵将军不知道藏匿地点｜已知部分：林侍卫只知道密函存在，不知内容｜误解：赵将军误以为密函已烧毁｜怀疑：陆衡怀疑有人转移密函但未证实｜知情：来客知道地点｜获知条件：亲自找到密函或收到知情者可靠告知';
const nobody='没有人知道密室钥匙已被换掉。';
let state=W.PlainMemory.normalize({storageFormat:'sentences-v1',initialized:true,memory:{knowledge:[secret,nobody],characters:['陆衡｜位置：西院'],world:['时间：2026-09-10｜位置：西院']}});
const before=JSON.stringify(state);
const html=W.MemoryView.render(state,'knowledge');
assert.ok(html.indexOf('<small>不知情者</small>') < html.indexOf('<small>知情者</small>'));
assert.ok(html.includes('只知道的部分'));
assert.ok(html.includes('获知条件'));
assert.ok(html.includes('误以为密函已烧毁'));
assert.equal(JSON.stringify(state),before,'knowledge view cannot invent or mutate boundaries');
const alias=W.MemoryView._test.parse('密函｜不知道：陆衡不知地点｜部分知情：侍卫只知存在｜误解者：将军认为已焚毁');
assert.deepEqual(alias.fields.map(([key])=>key),['不知情','已知部分','误解']);
for(let turn=0;turn<12;turn++) {
    const receipt=[];
    const injection=Object.values(W.PlainMemory.composeByDepth(state,receipt)).join('\n');
    assert.ok(injection.includes(secret),'complete boundary must remain injected after prior delivery, without matching keywords');
    assert.ok(injection.includes(nobody),'negative knowledge facts are not empty placeholders');
    assert.ok(injection.includes('作者或AI知道不等于人物知道'));
    state.runtime.sentenceDelivery=W.PlainMemory.commitDeliveryReceipt(state,receipt);
    state=W.PlainMemory.prepareSave(state,state,'test-unchanged');
}
assert.deepEqual(state.memory.knowledge,[secret,nobody],'no new evidence means no forgetting or automatic disclosure');
const learned=secret.replace('陆衡、赵将军不知道藏匿地点','赵将军不知道藏匿地点').replace('陆衡怀疑有人转移密函但未证实','陆衡经来客告知已确认地点').replace('来客知道地点','来客、陆衡知道地点');
state=W.PlainMemory.apply(state,[{module:'knowledge',before:secret,text:learned}]).state;
const updated=Object.values(W.PlainMemory.composeByDepth(state)).join('\n');
assert.ok(updated.includes('赵将军不知道藏匿地点'));
assert.ok(updated.includes('林侍卫只知道密函存在，不知内容'));
assert.ok(updated.includes(nobody));
settings.injectionModules.knowledge.enabled=false;
assert.ok(!Object.values(W.PlainMemory.composeByDepth(state)).join('\n').includes(learned),'explicit module opt-out is respected');
settings.injectionModules.knowledge.enabled=true;
const onlyNegative=W.PlainMemory.normalize({storageFormat:'sentences-v1',memory:{knowledge:[nobody]}});
assert.ok(!W.PlainMemory._test.missingModules(onlyNegative).includes('knowledge'),'specific unknown-to-character facts fill knowledge, not a placeholder');
let prompt='';
W.Api={complete:async system=>{prompt=system;return {factStream:{facts:[],end:true}};}};
await W.PlainMemory._test.request('测试',{memory:state.memory});
assert.ok(prompt.includes('知识/秘密栏以“不知道的边界”为重点'));
assert.ok(prompt.includes('没有写知情者不等于已证明其他所有人不知情'));
assert.ok(prompt.includes('告诉甲不自动告诉乙'));
assert.ok(prompt.includes('所有相关人物确已获知时保留实际公开范围，不虚构不知情者'));
console.log('Knowledge boundaries passed: unknown/partial/mistaken first, persistent complete injection, negative facts, per-person update, no invented ignorance and shared extraction instructions. Real API calls: 0.');
